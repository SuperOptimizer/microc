#!/usr/bin/env python3
# Generates libc/src/mathtab.h: the tables and polynomial coefficients of the math library.
# usage: python3 tests/ext/libm/mktab.py > libc/src/mathtab.h     (needs mpmath)
import sys
from mpmath import mp, mpf
import mpmath
mp.prec = 400

def rn(x):
    "nearest double"
    x = mpf(x)
    if x == 0: return 0.0
    with mp.workprec(53):
        y = +x
    return float(y)
def hx(x):
    return float(x).hex()
def dd(x):
    h = rn(x); return h, rn(mpf(x) - mpf(h))
def trunc_to(x, bit):
    "x rounded to a multiple of 2^bit"
    return float(mpmath.nint(mpf(x) / mpf(2)**bit) * mpf(2)**bit)
out = []; tabs = []; xtabs = []
XNAMES = ("expm1_poly", "erf_poly", "erf_tab", "erfcx_tab", "stirling_poly", "lgam1_poly", "lgam2_poly", "cbrt_poly")  # used by mathx.c
cur = [tabs]
def emit(s): out.append(s)
def temit(s): cur[0].append(s)
def arr(name, vals, per=4):
    cur[0] = xtabs if name in XNAMES else tabs
    temit("static const double %s[%d] = {" % (name, len(vals)))
    for i in range(0, len(vals), per):
        temit("    " + ", ".join(hx(v) for v in vals[i:i+per]) + ",")
    temit("};")
def arr2(name, rows, glob=True):
    cur[0] = xtabs if name in XNAMES else tabs
    temit("%sconst double %s[%d][%d] = {" % ("" if glob else "static ", name, len(rows), len(rows[0])))
    for r in rows:
        temit("    {" + ", ".join(hx(v) for v in r) + "},")
    temit("};")
def const(name, v):
    emit("#define %s %s" % (name, hx(v)))
def constdd(name, x):
    h, l = dd(x); const(name + "_H", h); const(name + "_L", l)

def fit(f, a, b, tol, nmin=2, nmax=40):
    "polynomial in t = x - a on [a,b] (coefficients lowest first), absolute error < tol"
    g = lambda t: f(a + t)
    for n in range(nmin, nmax):
        c, err = mpmath.chebyfit(g, [0, b - a], n, error=True)
        if err < tol:
            return [rn(v) for v in reversed(c)]
    raise Exception("no fit")
def fitc(f, c, h, tol, nmin=2, nmax=40):
    "polynomial in t = x - c on [c-h,c+h]"
    g = lambda t: f(c + t)
    for n in range(nmin, nmax):
        co, err = mpmath.chebyfit(g, [-h, h], n, error=True)
        if err < tol:
            return list(reversed(co))
    raise Exception("no fit")

emit("/* Tables of the math library. Generated by tests/ext/libm/mktab.py; do not edit. */")
ln2 = mp.ln2; pi = mp.pi

# ---- exp: 2^(i/128) as hi+lo; ln2/128 in two parts
arr2("__math_exp_tab", [dd(mpf(2)**(mpf(i)/128)) for i in range(128)])
const("EXP_INVL", rn(128/ln2))
l1 = trunc_to(ln2/128, -40); const("EXP_L1", l1); const("EXP_L2", rn(ln2/128 - mpf(l1)))
const("EXP2_C", rn(ln2))
a = mpmath.log10(2)/128
const("EXP10_INVL", rn(1/a)); a1 = trunc_to(a, -42); const("EXP10_A1", a1); const("EXP10_A2", rn(a - mpf(a1)))
constdd("LN10", mp.ln10)
arr("expm1_poly", [rn(1/mpmath.factorial(n)) for n in range(3, 15)])
arr("sinh_poly", [rn(1/mpmath.factorial(n)) for n in range(3, 19, 2)])
def tanh_f(z):
    if z == 0: return mpf(-1)/3
    s = mpmath.sqrt(z); return (mpmath.tanh(s)/s - 1)/z
arr("tanh_poly", fit(tanh_f, 0, mpf(1)/16, mpf(2)**-62))

# ---- log: z in [OFF, 2 OFF) cut into 128 pieces; invc ~ 1/centre, -log(invc) as hi+lo
OFF = 0x3ff0000000000000 - (75 << 45) - ((2 << 45) // 3)
emit("#define LOG_OFF 0x%xUL" % OFF)
import struct
def bits2d(u): return struct.unpack("<d", struct.pack("<Q", u))[0]
rows = []; maxr = 0
for i in range(128):
    lo = bits2d(OFF + (i << 45)); hi = bits2d(OFF + ((i + 1) << 45) - 1)
    if lo < 1.0 <= hi or lo <= 1.0 < hi: invc = 1.0
    else: invc = trunc_to(2/(mpf(lo) + mpf(hi)), -20)
    for z in (lo, hi): maxr = max(maxr, abs(mpf(z)*invc - 1))
    lc = -mpmath.log(mpf(invc)); h = trunc_to(lc, -42)
    rows.append((invc, h, rn(lc - mpf(h))))
emit("/* max |r| = %s */" % mpmath.nstr(maxr, 5))
arr2("__math_log_tab", rows)
h = trunc_to(ln2, -42); const("LN2_H42", h); const("LN2_L42", rn(ln2 - mpf(h)))
constdd("LN2", ln2)
constdd("INVLN2", 1/ln2); constdd("INVLN10", 1/mp.ln10)
l = mpmath.log10(2); h = trunc_to(l, -42); const("LOG10_2_H42", h); const("LOG10_2_L42", rn(l - mpf(h)))
arr("log_poly", [rn(mpf((-1)**(n+1))/n) for n in range(3, 12)])

# ---- trigonometric
constdd("PIO2", pi/2); constdd("PI", pi); constdd("PIO4", pi/4)
const("INVPIO2", rn(2/pi))
p1 = trunc_to(pi/2, -32); p2 = trunc_to(pi/2 - mpf(p1), -65); p3 = rn(pi/2 - mpf(p1) - mpf(p2))
const("PIO2_1", p1); const("PIO2_2", p2); const("PIO2_3", p3)
# 2/pi: 64 zero bits, then the fraction bits
nb = 1600
with mp.workprec(nb + 100):
    v = int(mpmath.floor(2/mp.pi * mpf(2)**nb))
ws = [0] + [(v >> (nb - 64*(i+1))) & 0xffffffffffffffff for i in range(nb // 64)]
cur[0] = tabs
temit("static const unsigned long twoopi_bits[%d] = {" % len(ws))
for i in range(0, len(ws), 3):
    temit("    " + ", ".join("0x%016xUL" % w for w in ws[i:i+3]) + ",")
temit("};")
q = (pi/4)**2
def sin_f(z):
    if z == 0: return mpf(-1)/6
    s = mpmath.sqrt(z); return (mpmath.sin(s)/s - 1)/z
def cos_f(z):
    if z == 0: return mpf(1)/24
    s = mpmath.sqrt(z); return (mpmath.cos(s) - 1 + z/2)/(z*z)
arr("sin_poly", fit(sin_f, 0, q*1.01, mpf(2)**-62))
# sin and cos of i/64 as hi+lo, for i = 16 .. 52 (the kernel uses the polynomial below 1/4)
arr2("sin_tab", [list(dd(mpmath.sin(mpf(i)/64))) + list(dd(mpmath.cos(mpf(i)/64))) for i in range(16, 53)], glob=False)
arr("cos_poly", fit(cos_f, 0, q*1.01, mpf(2)**-62))
arr2("__math_atan_tab", [dd(mpmath.atan(mpf(i)/64)) for i in range(65)])
def asin_f(z):
    if z == 0: return mpf(1)/6
    s = mpmath.sqrt(z); return (mpmath.asin(s)/s - 1)/z
arr("asin_poly", fit(asin_f, 0, mpf(1)/4, mpf(2)**-61))

# ---- erf, erfc
mp.prec = 250
constdd("TWO_SQRTPI", 2/mpmath.sqrt(pi))
def erf_f(z):
    if z == 0: return -2/mpmath.sqrt(pi)/3
    s = mpmath.sqrt(z); return (mpmath.erf(s)/s - 2/mpmath.sqrt(pi))/z
arr("erf_poly", fit(erf_f, 0, mpf(1)/16, mpf(2)**-63))
def pieces(name, f, first, octaves, tol, rel):
    "8 pieces per octave from 2^first on; rows: f(centre) as hi+lo, then the coefficients of (x - centre)^k"
    rows = []
    for o in range(octaves):
        for j in range(8):
            w = mpf(2)**(first + o) / 8
            c = mpf(2)**(first + o) + w*j + w/2
            co = fitc(f, c, w/2, tol * (abs(f(c)) if rel else 1), nmin=6)
            h, l = dd(co[0])
            rows.append([h, l] + [rn(v) for v in co[1:]])
    n = max(len(r) for r in rows)
    rows = [r + [0.0]*(n - len(r)) for r in rows]
    arr2(name, rows, glob=False)
    emit("#define %s_N %d" % (name.upper(), n - 2))
pieces("erf_tab", mpmath.erf, -2, 5, mpf(2)**-64, False)
pieces("erfcx_tab", lambda x: mpmath.exp(x*x)*mpmath.erfc(x), -1, 6, mpf(2)**-64, True)

# ---- gamma
constdd("HALF_LN2PI", mpmath.log(2*pi)/2)
constdd("LNPI", mpmath.log(pi))
constdd("EULER", mpmath.euler)
constdd("ONE_M_EULER", 1 - mpmath.euler)
def stirling_f(v):
    "x (lgamma(x) - ((x - 1/2) log x - x + log(2 pi)/2)) at v = 1/x^2"
    if v == 0: return mpf(1)/12
    with mp.workprec(600):
        x = 1/mpmath.sqrt(v)
        return +(x*(mpmath.loggamma(x) - ((x - 0.5)*mpmath.log(x) - x + mpmath.log(2*pi)/2)))
for n in range(4, 30):
    co, err = mpmath.chebyfit(stirling_f, [0, mpf(1)/144], n, error=True)
    if err < mpf(2)**-62: break
co = list(reversed(co))
constdd("STIRLING_C0", co[0])  # 1/12, nearly
arr("stirling_poly", [rn(v) for v in co[1:]])
constdd("LGAM1_A2", mpmath.zeta(2)/2)
constdd("LGAM2_A2", (mpmath.zeta(2) - 1)/2)
def lg1(t):
    "lgamma(1 + t) = -euler t + zeta(2)/2 t^2 + t^3 f(t)"
    if t == 0: return -mpmath.zeta(3)/3
    with mp.workprec(800):
        return +(((mpmath.loggamma(1 + t)/t + mpmath.euler)/t - mpmath.zeta(2)/2)/t)
def lg2(t):
    "lgamma(2 + t) = (1 - euler) t + (zeta(2) - 1)/2 t^2 + t^3 f(t)"
    if t == 0: return -(mpmath.zeta(3) - 1)/3
    with mp.workprec(800):
        return +(((mpmath.loggamma(2 + t)/t - (1 - mpmath.euler))/t - (mpmath.zeta(2) - 1)/2)/t)
arr("lgam1_poly", [rn(v) for v in fitc(lg1, 0, mpf(1)/8, mpf(2)**-58)])
arr("lgam2_poly", [rn(v) for v in fitc(lg2, 0, mpf(1)/8, mpf(2)**-58)])
mp.prec = 400
arr("cbrt_poly", [rn(v) for v in fitc(mpmath.cbrt, mpf(3)/2, mpf(1)/2, mpf(2)**-17)])
sys.stdout.write("\n".join(out) + "\n#ifdef MATHTAB_CORE\n" + "\n".join(tabs) + "\n#endif\n#ifdef MATHTAB_X\n" + "\n".join(xtabs) + "\n#endif\n")
