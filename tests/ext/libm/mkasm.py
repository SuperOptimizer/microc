#!/usr/bin/env python3
# Generates the hardware-instruction stubs of the math library, in two groups: what the C89 part of the
# library needs (floor, ceil, and fma under a reserved name), and the C99 names.
#   libc/sys/math_arm64.s, math99_arm64.s      Darwin (mcc's Mach-O assembler knows few FP mnemonics, so the words are spelled out)
#   the __asm__ blocks in libc/src/math.c and math99.c between the "BEGIN/END generated stubs" markers (Linux)
# usage: python3 tests/ext/libm/mkasm.py   (from the top of the tree; needs the host cc and otool)
import subprocess, os, re, tempfile
core = [
 (["__math_fma"], ["fmadd d0, d0, d1, d2"]),
 (["floor"], ["frintm d0, d0"]),
 (["ceil"], ["frintp d0, d0"]),
]
c99 = [
 (["fma", "fmal"], ["fmadd d0, d0, d1, d2"]),
 (["fmaf"], ["fmadd s0, s0, s1, s2"]),
 (["sqrtf"], ["fsqrt s0, s0"]),
 (["fabsf"], ["fabs s0, s0"]),
 (["floorl"], ["frintm d0, d0"]), (["floorf"], ["frintm s0, s0"]),
 (["ceill"], ["frintp d0, d0"]), (["ceilf"], ["frintp s0, s0"]),
 (["trunc", "truncl"], ["frintz d0, d0"]), (["truncf"], ["frintz s0, s0"]),
 (["round", "roundl"], ["frinta d0, d0"]), (["roundf"], ["frinta s0, s0"]),
 (["rint", "rintl"], ["frintx d0, d0"]), (["rintf"], ["frintx s0, s0"]),
 (["nearbyint", "nearbyintl"], ["frinti d0, d0"]), (["nearbyintf"], ["frinti s0, s0"]),
 (["lrint", "llrint", "lrintl", "llrintl"], ["frintx d0, d0", "fcvtzs x0, d0"]),
 (["lrintf", "llrintf"], ["frintx s0, s0", "fcvtzs x0, s0"]),
 (["lround", "llround", "lroundl", "llroundl"], ["fcvtas x0, d0"]),
 (["lroundf", "llroundf"], ["fcvtas x0, s0"]),
 (["fmin", "fminl"], ["fminnm d0, d0, d1"]), (["fminf"], ["fminnm s0, s0, s1"]),
 (["fmax", "fmaxl"], ["fmaxnm d0, d0, d1"]), (["fmaxf"], ["fmaxnm s0, s0, s1"]),
 (["__math_getfpcr"], ["mrs x0, fpcr"]), (["__math_setfpcr"], ["msr fpcr, x0"]),
 (["__math_getfpsr"], ["mrs x0, fpsr"]), (["__math_setfpsr"], ["msr fpsr, x0"]),
]
def words(ins):
    d = tempfile.mkdtemp(dir="build/test/ulibm")
    s = os.path.join(d, "t.s"); o = os.path.join(d, "t.o")
    open(s, "w").write(".text\n" + "".join(" %s\n" % i for i in ins))
    subprocess.check_call(["cc", "-c", s, "-o", o])
    out = subprocess.check_output(["otool", "-t", o]).decode()
    w = []
    for line in out.splitlines():
        p = line.split()
        if len(p) > 1 and re.fullmatch(r"[0-9a-f]{16}", p[0]):
            w += p[1:]
    os.remove(s); os.remove(o); os.rmdir(d)
    assert len(w) == len(ins), (ins, w)
    return w
def write(stubs, sfile, cfile, what):
    dar = ["// Math functions that are one machine instruction: " + what + ". Generated by tests/ext/libm/mkasm.py; do not edit.",
           "// (The instructions are given as words because this assembler knows only the mnemonics the compiler emits.)", ".text"]
    lx = []
    for names, ins in stubs:
        ins = ins + ["ret"]
        w = words(ins)
        for n in names:
            dar.append(".globl _" + n)
        dar.append(".align 2")
        for n in names:
            dar.append("_" + n + ":")
        for i, x in zip(ins, w):
            dar.append("    .long 0x%s // %s" % (x, i))
        l = "".join(".globl %s\\n.type %s,%%function\\n" % (n, n) for n in names)
        l += "".join("%s:\\n" % n for n in names) + "".join(" %s\\n" % i for i in ins)
        lx.append('    "' + l + '"')
    open(sfile, "w").write("\n".join(dar) + "\n")
    block = "/* BEGIN generated stubs */\n__asm__(\".text\\n.balign 4\\n\"\n" + "\n".join(lx) + ");\n/* END generated stubs */\n"
    src = open(cfile).read()
    a = src.index("/* BEGIN generated stubs"); b = src.index("/* END generated stubs */") + len("/* END generated stubs */\n")
    open(cfile, "w").write(src[:a] + block + src[b:])
write(core, "libc/sys/math_arm64.s", "libc/src/math.c", "those that C89 programs get")
write(c99, "libc/sys/math99_arm64.s", "libc/src/math99.c", "the C99 names")
